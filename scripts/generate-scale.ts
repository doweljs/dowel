/**
 * Generates `packages/dowel/test/types/scale.test-d.ts`: 300 services in ten
 * layers, each depending on two services of the layer before, with scoped
 * and multi-binding slots, and executions whose entries reach services
 * nothing provided does. The roots reach through every layer, which keeps
 * the type-level model honest about instantiation depth and union sizes.
 * It is also the workload `type-budget.ts` measures.
 */
import { $ } from 'bun'

const SERVICES = 300
const LAYERS = 10
const EXECUTIONS = 5
const OUTPUT = new URL('../packages/dowel/test/types/scale.test-d.ts', import.meta.url)
const lines: string[] = [
	'// Generated by scripts/generate-scale.ts. Do not edit.',
	'// biome-ignore-all lint/correctness/noUnusedVariables: services off the root path are the point',
	"import { bind, container, execution, scope, service, slot } from '../../src/index.ts'",
	'',
	"const Logger = slot('Logger')<{ info(m: string): void }>()",
	"const Config = slot('Config')<{ url: string }>()",
	"const PerRequest = scope('request')",
	"const Request = slot('Request', { scope: PerRequest })<{ url: string }>()",
	"const Plugins = slot('Plugins', { many: true })<{ name: string }>()",
	"const Job = scope('job')",
	"const JobInput = slot('JobInput', { scope: Job })<{ id: string }>()",
	'',
]
const perLayer = Math.ceil(SERVICES / LAYERS)
for (let i = 0; i < SERVICES; i++) {
	const layer = Math.floor(i / perLayer)
	const deps: string[] = ['log: Logger']
	if (layer === 0) deps.push('config: Config')
	else {
		// Two services of the previous layer, spread so that the roots reach most of the graph.
		const previous = (layer - 1) * perLayer
		deps.push(
			`a: S${previous + ((i * 7) % perLayer)}`,
			`b: S${previous + ((i * 7 + 3) % perLayer)}`,
		)
	}
	if (i % 37 === 0) deps.push('plugins: Plugins')
	if (i === SERVICES - 1) deps.push('req: Request')
	lines.push(`const S${i} = service('S${i}', { ${deps.join(', ')} }, (d) => ({ id: ${i}, d }))`)
}
// Each entry reaches a service of the last layer that only executions reach, and the layers below it.
lines.push('')
const runners: string[] = []
for (let k = 0; k < EXECUTIONS; k++) {
	lines.push(
		`const Entry${k} = service('Entry${k}', { input: JobInput, top: S${SERVICES - 3 - k} }, (d) => d)`,
		`const Run${k} = execution('Run${k}', { scope: Job, entry: Entry${k}, inputs: { input: JobInput } })`,
	)
	runners.push(`run${k}: Run${k}`)
}
lines.push(
	`const Scheduler = service('Scheduler', { ${runners.join(', ')} }, (d) => d)`,
	'',
	'const app = await container()',
	`\t.provide(S${SERVICES - 1}, S${SERVICES - 2}, Scheduler)`,
	'\t.bind(Logger, { info() {} })',
	"\t.bind(Config, { url: '' })",
	"\t.contribute(Plugins, { name: 'a' })",
	'\t.build()',
	`export const deep = (await app.open(PerRequest, bind(Request, { url: '/' }))).get(S${SERVICES - 1}).d.a.id`,
	"export const ran = app.get(Scheduler).run0({ input: { id: 'x' } }, (entry) => entry.top.d.a.id)",
	'// @ts-expect-error: the rest of the last layer is not reachable from the roots',
	`app.get(S${SERVICES - 3 - EXECUTIONS})`,
	'',
)
await Bun.write(OUTPUT, lines.join('\n'))
await $`bunx biome format --write ${OUTPUT.pathname}`.quiet()
console.log(`wrote scale.test-d.ts with ${SERVICES} services`)
